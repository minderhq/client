const WORDS = "/[A-Za-z]{2,}/";
const READ_ATTRS =
  "/^(aria-label|aria-description|aria-valuetext|title|placeholder|alt|label|subtitle)$/";
const HARDCODED_TEXT_MESSAGE =
  "Hard-coded user-facing text: put it in the message catalogs (src/i18n/messages) and render it with t() from useI18n().";
const HARDCODED_TEXT_SELECTORS = [
  `JSXText[value=${WORDS}]:not([value=/^\\s*Minder\\s*$/])`,
  `:matches(JSXElement, JSXFragment) > JSXExpressionContainer > Literal[value=${WORDS}]`,
  `:matches(JSXElement, JSXFragment) > JSXExpressionContainer > :matches(ConditionalExpression, LogicalExpression) > Literal[value=${WORDS}]`,
  `:matches(JSXElement, JSXFragment) > JSXExpressionContainer > TemplateLiteral > TemplateElement[value.raw=${WORDS}]`,
  `JSXAttribute[name.name=${READ_ATTRS}] > Literal[value=${WORDS}]`,
  `JSXAttribute[name.name=${READ_ATTRS}] > JSXExpressionContainer > Literal[value=${WORDS}]`,
  `JSXAttribute[name.name=${READ_ATTRS}] > JSXExpressionContainer > TemplateLiteral > TemplateElement[value.raw=${WORDS}]`,
].map((selector) => ({ selector, message: HARDCODED_TEXT_MESSAGE }));

